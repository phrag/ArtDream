"""Generates the fArtSaver logo vector drawables: launcher icon layers, TV banner
and the settings-nav lockup.

    pip install fonttools uharfbuzz
    python3 tools/logo/gen.py [out_dir]   # default app/src/main/res/drawable

The wordmark is set in Inter Display Bold (SIL OFL) and baked into paths, since
vector drawables can't render text. Point BOLD at the font if it isn't installed
system-wide.
"""
import math, sys, uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

OUT = sys.argv[1] if len(sys.argv) > 1 else "app/src/main/res/drawable"
AMBER, CORAL = "#FFF0B45A", "#FFFF6B5A"
TEXT = "#FFF2F3F5"

def n(v): return f"{v:.2f}".rstrip("0").rstrip(".")

def rrect(x, y, w, h, r):
    return (f"M{n(x+r)},{n(y)}H{n(x+w-r)}A{n(r)},{n(r)} 0 0 1 {n(x+w)},{n(y+r)}V{n(y+h-r)}"
            f"A{n(r)},{n(r)} 0 0 1 {n(x+w-r)},{n(y+h)}H{n(x+r)}A{n(r)},{n(r)} 0 0 1 {n(x)},{n(y+h-r)}"
            f"V{n(y+r)}A{n(r)},{n(r)} 0 0 1 {n(x+r)},{n(y)}Z")

def mark_paths(x0, y0, s):
    """The mark in a 48-unit box at (x0,y0), scaled to s units: a rounded frame
    holding a setting sun cut by horizon stripes. Returns (frame, sun) paths."""
    k = s / 48
    X = lambda v: x0 + v * k
    Y = lambda v: y0 + v * k
    frame = rrect(X(0), Y(0), 48*k, 48*k, 12*k) + rrect(X(5), Y(5), 38*k, 38*k, 7*k)
    cx, cy, r = 24, 30, 13
    w = lambda y: math.sqrt(max(r*r - (y-cy)**2, 0))
    R = n(r*k)
    y1 = 32
    sun = (f"M{n(X(cx-w(y1)))},{n(Y(y1))}A{R},{R} 0 1 1 {n(X(cx+w(y1)))},{n(Y(y1))}Z")
    for a, b in [(34.5, 37), (39.5, 41.5)]:
        sun += (f"M{n(X(cx-w(a)))},{n(Y(a))}H{n(X(cx+w(a)))}A{R},{R} 0 0 1 {n(X(cx+w(b)))},{n(Y(b))}"
                f"H{n(X(cx-w(b)))}A{R},{R} 0 0 1 {n(X(cx-w(a)))},{n(Y(a))}Z")
    return frame, sun

def grad(x1, y1, x2, y2, stops):
    items = "\n".join(f'                <item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return f'''        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="{n(x1)}" android:startY="{n(y1)}"
                android:endX="{n(x2)}" android:endY="{n(y2)}">
{items}
            </gradient>
        </aapt:attr>'''

def gpath(d, g, even=False, indent="    "):
    ft = '\n        android:fillType="evenOdd"' if even else ""
    return f'''{indent}<path{ft}
        android:pathData="{d}">
{g}
    </path>'''

def spath(d, color, even=False):
    ft = '\n        android:fillType="evenOdd"' if even else ""
    return f'''    <path{ft}
        android:fillColor="{color}"
        android:pathData="{d}" />'''

def mark_xml(x0, y0, s):
    frame, sun = mark_paths(x0, y0, s)
    g = grad(x0, y0, x0+s, y0+s, [(0, AMBER), (1, CORAL)])
    gs = grad(0, y0+17/48*s, 0, y0+43/48*s, [(0, AMBER), (1, CORAL)])
    return gpath(frame, g, even=True) + "\n" + gpath(sun, gs)

def text_paths(fontfile, txt, x, baseline, cap, track=0.0):
    """Glyph outlines of txt, cap height `cap`, starting at x on `baseline`.
    Returns ([path per char], width)."""
    blob = hb.Blob.from_file_path(fontfile)
    font = hb.Font(hb.Face(blob))
    buf = hb.Buffer(); buf.add_str(txt); buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": False})
    tt = TTFont(fontfile); gs = tt.getGlyphSet(); order = tt.getGlyphOrder()
    sc = cap / tt["OS/2"].sCapHeight
    pen_x = 0; out = []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        p = SVGPathPen(gs, ntos=lambda v: n(v))
        gs[order[info.codepoint]].draw(TransformPen(p, (sc, 0, 0, -sc, x + (pen_x + pos.x_offset) * sc, baseline)))
        out.append(p.getCommands())
        pen_x += pos.x_advance + track * tt["head"].unitsPerEm
    return out, (pen_x - track * tt["head"].unitsPerEm) * sc

BOLD = "/usr/share/fonts/opentype/inter/InterDisplay-Bold.otf"

def wordmark_xml(x, baseline, cap):
    g, w = text_paths(BOLD, "fArtSaver", x, baseline, cap, track=-0.01)
    return spath(g[0], AMBER) + "\n" + spath("".join(g[1:]), TEXT), w

def wordmark_width(cap):
    return text_paths(BOLD, "fArtSaver", 0, 0, cap, track=-0.01)[1]

HEAD = '''<?xml version="1.0" encoding="utf-8"?>
{comment}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"{tools}
    android:width="{w}dp"
    android:height="{h}dp"
    android:viewportWidth="{w}"
    android:viewportHeight="{h}">
'''
BG = [(0, "#FF171B24"), (1, "#FF0B0D11")]

def write(name, body, w, h, comment, tools=""):
    with open(f"{OUT}/{name}", "w") as f:
        f.write(HEAD.format(comment=comment, w=w, h=h, tools=tools) + body + "\n</vector>\n")

GEN = "Generated by tools/logo/gen.py; edit that script, not this file."

# --- launcher icon ---
write("ic_launcher_background.xml",
      gpath("M0,0H108V108H0Z", grad(0, 0, 108, 108, BG)), 108, 108,
      f"<!-- Adaptive launcher icon background: near-black ink with a soft top-left lift.\n     {GEN} -->")
write("ic_launcher_foreground.xml", mark_xml(30, 30, 48), 108, 108,
      f"<!-- Adaptive launcher icon foreground: the fArtSaver mark (a rounded frame\n     holding a setting sun), inside the 66dp safe zone.\n     {GEN} -->")
fr, sun = mark_paths(30, 30, 48)
write("ic_launcher_monochrome.xml", spath(fr, "#FF000000", even=True) + "\n" + spath(sun, "#FF000000"), 108, 108,
      f"<!-- Themed-icon (Android 13+) layer: the mark in one colour; the launcher tints it.\n     {GEN} -->")

# --- TV banner 320x180 ---
cap = 30
ww = wordmark_width(cap)
ms = 64
gap = 18
total = ms + gap + ww
x0 = (320 - total) / 2
my = (180 - ms) / 2
body = gpath("M0,0H320V180H0Z", grad(0, 0, 320, 180, BG)) + "\n" + mark_xml(x0, my, ms) + "\n"
# Wordmark: baseline so caps are centred on the mark.
wm, _ = wordmark_xml(x0 + ms + gap, 90 + cap / 2, cap)
body += wm
write("banner.xml", body, 320, 180,
      f"<!-- Leanback banner, 320x180dp: the fArtSaver mark beside the wordmark.\n"
      f"     Wordmark glyphs are outlines of Inter Display Bold (SIL OFL).\n"
      f"     VectorRaster is suppressed: the size is the TV banner spec, and minSdk 26\n"
      f"     never needs the raster fallback that check guards.\n     {GEN} -->",
      tools='\n    xmlns:tools="http://schemas.android.com/tools"\n    tools:ignore="VectorRaster"')

# --- in-app lockup for the settings nav ---
cap = 22
ww = wordmark_width(cap)
ms = 36; gap = 12; H = 40
W = math.ceil(ms + gap + ww + 1)
body = mark_xml(0, (H - ms) / 2, ms) + "\n"
wm, _ = wordmark_xml(ms + gap, H / 2 + cap / 2, cap)
write("logo_lockup.xml", body + wm, W, H,
      f"<!-- Settings nav header: the fArtSaver mark and wordmark on a transparent ground.\n     {GEN} -->")
